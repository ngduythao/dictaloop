import { t } from './i18n';
import { parseSubtitles, type Sentence } from './subtitles';

// Reading lessons that come from links: YouTube (subtitles through the
// transcript API) or a direct media file with an optional subtitle link.

// The static build has no server for the transcript route, so it uses the original
// author's deployment; `npm run dev` serves app/api/youtube/transcript itself.
const transcriptApiBase = process.env.NODE_ENV === 'production' ? 'https://listen-write-quinn-studio.quinn-chen-12138.chatgpt.site' : '';

export function youtubeVideoId(url: URL): string {
  const hostname = url.hostname.replace(/^www\./, '');
  let id = '';
  if (hostname === 'youtu.be') id = url.pathname.split('/').filter(Boolean)[0] || '';
  if (['youtube.com', 'm.youtube.com', 'music.youtube.com', 'youtube-nocookie.com'].includes(hostname)) {
    id = url.searchParams.get('v') || url.pathname.match(/^\/(?:embed|shorts|live)\/([\w-]{11})/)?.[1] || '';
  }
  return /^[\w-]{11}$/.test(id) ? id : '';
}

export function parseHttpUrl(value: string): URL {
  let url: URL;
  try { url = new URL(value.trim()); } catch { throw new Error(t('url.invalid')); }
  if (!['http:', 'https:'].includes(url.protocol)) throw new Error(t('url.invalid'));
  if (/(^|\.)pan\.baidu\.com$/.test(url.hostname)) throw new Error(t('baidu.unsupported'));
  return url;
}

export type YouTubeTranscript = { title: string; duration: number; sentences: Sentence[]; label: string };

export async function fetchYouTubeTranscript(id: string): Promise<YouTubeTranscript> {
  const response = await fetch(`${transcriptApiBase}/api/youtube/transcript?id=${encodeURIComponent(id)}&segmentation=2`, { signal: AbortSignal.timeout(30000) });
  const data = await response.json() as { title?: string; duration?: number; label?: string; autoGenerated?: boolean; sentences?: Sentence[]; error?: string };
  if (!response.ok) throw new Error(data.error || t('yt.subsFailed'));
  const sentences = data.sentences || [];
  if (!sentences.length) throw new Error(t('yt.noSentences'));
  return {
    title: data.title || `YouTube · ${id}`,
    duration: data.duration || sentences.at(-1)?.end || 0,
    sentences,
    label: `YouTube ${data.autoGenerated ? t('yt.autoSubs') : t('yt.enSubs')} · ${data.label || 'English'}`,
  };
}

export async function fetchSubtitles(value: string): Promise<Sentence[]> {
  let url: URL;
  try { url = new URL(value.trim()); } catch { throw new Error(t('subs.badUrl')); }
  if (!['http:', 'https:'].includes(url.protocol)) throw new Error(t('subs.badUrl'));
  const response = await fetch(url, { signal: AbortSignal.timeout(15000) });
  if (!response.ok) throw new Error(t('subs.unreachable'));
  const sentences = parseSubtitles(await response.text());
  if (!sentences.length) throw new Error(t('subs.notSubtitle'));
  return sentences;
}

export function titleFromUrl(url: URL): string {
  const last = decodeURIComponent(url.pathname.split('/').filter(Boolean).pop() || '');
  return last.replace(/\.[^.]+$/, '').replace(/[_-]+/g, ' ').trim() || url.hostname;
}

// Reads only the media's metadata (no CORS needed) to learn its length.
export function probeDuration(src: string, timeoutMs = 15000): Promise<number | undefined> {
  return new Promise(resolve => {
    const media = document.createElement('audio');
    const done = (value?: number) => {
      clearTimeout(timer);
      media.removeAttribute('src');
      media.load();
      resolve(value && Number.isFinite(value) ? value : undefined);
    };
    const timer = setTimeout(() => done(), timeoutMs);
    media.preload = 'metadata';
    media.onloadedmetadata = () => done(media.duration);
    media.onerror = () => done();
    media.src = src;
  });
}
